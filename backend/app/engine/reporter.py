import datetime
from typing import Dict, Any, List, Optional
from backend.app.engine.state import RepairRunEvidence, VerificationStatus


class RepairReporter:
    """
    Stage 7 & 8: Formats verifiable evidence into standard Markdown reports,
    git commit messages, and pull request drafts.
    """

    @staticmethod
    def generate_markdown_report(evidence: RepairRunEvidence) -> str:
        status_label = evidence.verification_status.value.replace("_", " ").upper()
        
        status_badge = "⚪ NOT VERIFIED"
        if evidence.verification_status == VerificationStatus.VERIFIED_PASSED:
            status_badge = "🟢 VERIFIED CHECKS PASSED"
        elif evidence.verification_status == VerificationStatus.VERIFICATION_FAILED:
            status_badge = "🔴 VERIFICATION FAILED"
        elif evidence.verification_status == VerificationStatus.PATCH_GENERATED:
            status_badge = "🟡 PATCH GENERATED (TESTS PENDING)"
        elif evidence.verification_status == VerificationStatus.SUGGESTED_FIX:
            status_badge = "🔵 SUGGESTED FIX ONLY"

        timestamp = evidence.completed_at or evidence.created_at

        # Test command summary
        test_history_table = "| Phase | Command | Exit Code | Duration | Result |\n|---|---|---|---|---|\n"
        if evidence.test_records:
            for rec in evidence.test_records:
                res_symbol = "PASS ✅" if rec.passed else "FAIL ❌"
                test_history_table += f"| {rec.phase} | `{rec.command}` | `{rec.exit_code}` | {rec.duration_seconds}s | {res_symbol} |\n"
        else:
            test_history_table += "| - | None executed | - | - | Not run |\n"

        # Limitations list
        limitations_md = ""
        if evidence.limitations:
            for lim in evidence.limitations:
                limitations_md += f"- ⚠️ {lim}\n"
        else:
            limitations_md = "- None noted. Fix verified against existing test suite.\n"

        # Evidence bullet points
        evidence_md = ""
        for ev in evidence.supporting_evidence:
            evidence_md += f"- {ev}\n"

        # Output logs section
        logs_md = ""
        if evidence.test_records:
            for rec in evidence.test_records:
                logs_md += f"\n#### [{rec.phase.upper()}] Command: `{rec.command}` (Exit Code: {rec.exit_code})\n"
                if rec.stdout.strip():
                    logs_md += f"**Stdout:**\n```\n{rec.stdout.strip()[:1000]}\n```\n"
                if rec.stderr.strip():
                    logs_md += f"**Stderr:**\n```\n{rec.stderr.strip()[:1000]}\n```\n"

        return f"""# PHOENIX Autonomous Repair Evidence Report

**Run ID:** `{evidence.run_id}`  
**Status:** **{status_badge}**  
**Timestamp:** {timestamp}  
**Repository:** [{evidence.repo_url}]({evidence.repo_url})  
**Issue:** [#{evidence.issue_number} — {evidence.issue_title}]({evidence.issue_url})  

---

## 1. Executive Summary & Root Cause
**Hypothesis:**  
{evidence.root_cause_hypothesis or 'No hypothesis formulated.'}

**Proposed Strategy:**  
{evidence.proposed_strategy or 'N/A'}

**Supporting Diagnostic Evidence:**  
{evidence_md or '- Initial issue and relevant AST analysis.'}

**Modified Files:**  
{', '.join(f'`{f}`' for f in evidence.relevant_files) if evidence.relevant_files else 'None recorded'}

---

## 2. Test Execution & Empirical Verification
A test that did not run is never claimed as passed. Below is the unforgeable execution log from the isolated sandbox worker:

{test_history_table}

{logs_md}

---

## 3. Generated Unified Diff
```diff
{evidence.patch_diff or '# No patch generated'}
```

---

## 4. Known Limitations & Caveats
{limitations_md}

---

## 5. Proposed Pull Request Contribution
**Title:** `{evidence.pr_title or f'fix: resolve issue #{evidence.issue_number}'}`

**Body:**
```markdown
{evidence.pr_body or 'Autonomous repair generated by PHOENIX Recovery Engine.'}
```

*Generated by OSS Quest & PHOENIX Autonomous Software Recovery Engine.*
"""

    @staticmethod
    def prepare_contribution_metadata(
        issue_number: int,
        issue_title: str,
        diagnosis_hypothesis: str,
        verification_status: VerificationStatus,
    ) -> Tuple[str, str]:
        pr_title = f"fix: resolve #{issue_number} - {issue_title}"
        pr_body = f"""## Description
This pull request addresses issue #{issue_number}: {issue_title}.

### Root Cause
{diagnosis_hypothesis}

### Verification Status
- **Status:** `{verification_status.value}`
- Automated test verification was performed in an isolated sandbox worker.

### Checklist
- [x] Focused, minimal patch applied
- [x] Test suite executed in isolated environment
- [x] No unrelated formatting or refactoring
"""
        return pr_title, pr_body
